#!/usr/bin/env python3
"""yarn-niah smoke

1.5B, one cheap length and one expensive one: proves the whole path (clone, install, corpus, GPU, rope scaling, report) in about ten minutes.

Generated by kaggle/build_kernels.py - do not edit by hand.
Preset smoke on NvidiaTeslaT4, harness pinned to 63c4fa72d141cab2f92d8faeaf4ce6a8c0aa5c9b.

model  : Qwen/Qwen2.5-1.5B-Instruct
lengths: 4096,131072
depths : 0.25,0.5,0.75
extra  : (none)
"""
import collections
import glob
import importlib.metadata as md
import os
import subprocess
import sys

REPO_URL = "https://github.com/Nikita-prog-art/yarn-haystack.git"
COMMIT = "63c4fa72d141cab2f92d8faeaf4ce6a8c0aa5c9b"
WORK = "/kaggle/working"
MODEL = "Qwen/Qwen2.5-1.5B-Instruct"
LENGTHS = "4096,131072"
DEPTHS = "0.25,0.5,0.75"
EXTRA = []
MAX_NEW_TOKENS = 32
SLUG = "smoke"

def scratch_dir():
    """A writable, roomy directory that is NOT part of the kernel's output.

    Putting HF_HOME under /kaggle/working made `kernels output` fetch the entire
    model and dataset cache - hundreds of megabytes per pull, for data we already
    have. /kaggle/temp is scratch and stays out of the output.
    """
    for candidate in ("/kaggle/temp", "/tmp"):
        try:
            os.makedirs(candidate, exist_ok=True)
            return candidate
        except OSError:
            continue
    return os.path.join(WORK, "scratch")


os.environ.setdefault("HF_HOME", os.path.join(scratch_dir(), "hf"))
# Long-context prefill fragments the allocator; the OOM message itself suggests this.
os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")


def sh(cmd, check=True):
    """Stream a subprocess, and on failure raise with its last lines.

    A bare CalledProcessError hides the only thing worth reading.
    """
    print("$", " ".join(cmd), flush=True)
    tail = collections.deque(maxlen=40)
    with subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          text=True, bufsize=1) as proc:
        for line in proc.stdout:
            print(line, end="", flush=True)
            tail.append(line.rstrip())
        proc.wait()
    if check and proc.returncode:
        raise SystemExit("command failed ({}):\n  {}".format(proc.returncode, "\n  ".join(tail)))


def version(pkg):
    try:
        return md.version(pkg)
    except md.PackageNotFoundError:
        return None


def main():
    os.makedirs(WORK, exist_ok=True)
    os.chdir(WORK)

    # 1. Harness at the pinned commit. Pinning matters: these numbers get compared
    #    against a later run, and "main moved" explains nothing.
    if not os.path.isdir("yarn-haystack"):
        sh(["git", "clone", "-q", REPO_URL, "yarn-haystack"])
    os.chdir("yarn-haystack")
    sh(["git", "fetch", "-q", "--all"])
    sh(["git", "checkout", "-q", COMMIT])
    head = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    if head != COMMIT:
        raise SystemExit("harness is at {}, expected {}".format(head, COMMIT))
    sys.path.insert(0, os.getcwd())
    print("harness commit:", head)

    # 2. Install only what is missing. The image already ships a CUDA-matched torch,
    #    and upgrading matplotlib/datasets provokes conflicts with preinstalled tools
    #    for no benefit here.
    need = []
    tf = version("transformers")
    if tf is None or tuple(int(x) for x in tf.split(".")[:2]) < (4, 51):
        need.append("transformers>=4.51")
    for pkg in ("accelerate", "datasets", "bitsandbytes"):
        if version(pkg) is None:
            need.append(pkg)
    if need:
        print("pip install:", " ".join(need), flush=True)
        sh([sys.executable, "-m", "pip", "install", "-q", "-U", *need])
    else:
        print("nothing to install - using what the image ships")
    for pkg in ("transformers", "torch", "accelerate", "datasets", "bitsandbytes", "matplotlib"):
        print("  {:14s} {}".format(pkg, version(pkg)))

    import torch
    print("\ntorch {} | cuda {} | gpus {}".format(
        torch.__version__, torch.cuda.is_available(), torch.cuda.device_count()))
    for i in range(torch.cuda.device_count()):
        props = torch.cuda.get_device_properties(i)
        print("  gpu{}: {}, {:.1f} GiB".format(i, props.name, props.total_memory / 2 ** 30))
    if not torch.cuda.is_available():
        raise SystemExit("no CUDA - this kernel was pushed without a GPU")
    tf = version("transformers")
    if tf is None or tuple(int(x) for x in tf.split(".")[:2]) < (4, 51):
        raise SystemExit("need transformers>=4.51, have {}".format(tf))

    # 3. Preflight. Internet is off by default on Kaggle and is the usual cause of a
    #    one-second death; the corpus check separates a download problem from a
    #    harness problem.
    import urllib.request
    try:
        print("huggingface.co ->",
              urllib.request.urlopen("https://huggingface.co", timeout=20).status)
    except Exception as exc:
        raise SystemExit("no internet in this kernel: {!r} (Kaggle needs phone "
                         "verification for that)".format(exc))
    import niah
    text = niah.load_corpus(None, os.path.join(os.getcwd(), "cache"))
    print("corpus OK: {:.1f}M chars cached".format(len(text) / 1e6))

    # 4. Both arms on an identical grid. check=False so that one failing arm still
    #    leaves the other's results and the report: a killed 128k case should cost
    #    one case, not the session.
    results = os.path.join(WORK, "results")
    os.makedirs(results, exist_ok=True)
    common = ["--model", MODEL, "--lengths", LENGTHS, "--depths", DEPTHS,
              "--max-new-tokens", str(MAX_NEW_TOKENS), *EXTRA]
    for arm, extra in (("base", []), ("yarn", ["--factor", "4", "--original-max", "32768"])):
        out = os.path.join(results, "{}_{}.jsonl".format(arm, SLUG))
        print("\n" + "=" * 72 + "\n== ARM {}\n".format(arm) + "=" * 72, flush=True)
        sh([sys.executable, "-u", "run.py", *common, "--arm", arm, *extra, "--out", out],
           check=False)

    # 5. Report. analyze.py copes with a partial run, so this is worth doing even if
    #    an arm was cut short: you get the heatmap for whatever finished.
    found = sorted(glob.glob(os.path.join(results, "*.jsonl")))
    print("\nresult files:", found)
    if not found:
        raise SystemExit("no results were produced - read the output above")
    report = os.path.join(WORK, "report_" + SLUG)
    sh([sys.executable, "analyze.py", *found, "--outdir", report])
    summary = os.path.join(report, "summary.md")
    if os.path.exists(summary):
        print("\n" + open(summary, encoding="utf-8").read())
    print("\noutputs under", WORK, ":")
    for path in found + sorted(glob.glob(os.path.join(report, "*"))):
        print("  ", path)


if __name__ == "__main__":
    main()
