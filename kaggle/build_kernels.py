#!/usr/bin/env python3
"""Generate Kaggle kernels for the NIAH run, as plain scripts.

Kernels are generated rather than hand-written because each one must pin the exact
harness commit, and that pin changes whenever the harness does.

Why `kernel_type: "script"` and not a notebook: Kaggle executes pushed notebooks
through papermill + nbconvert, which adds a whole format layer - cell sources are
concatenated, so a line list that lost its trailing newlines glues a cell into one
long comment and the run reports COMPLETE having done nothing. Plain scripts have
no such layer, their tracebacks land in the log unedited, and the output is
ordinary stdout.

    python kaggle/build_kernels.py --commit <sha> [--user <kaggle-user>] [--only smoke]

Each preset runs BOTH arms on an identical grid, so the only variable between the
two JSONLs is the rope scaling.
"""
from __future__ import annotations

import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_URL = "https://github.com/Nikita-prog-art/yarn-haystack.git"

PRESETS = {
    "smoke": {
        "title": "yarn-niah smoke",
        "model": "Qwen/Qwen2.5-1.5B-Instruct",
        "lengths": "4096,131072",
        "depths": "0.25,0.5,0.75",
        "extra": [],
        "max_new_tokens": 32,
        "why": "1.5B, one cheap length and one expensive one: proves the whole path "
               "(clone, install, corpus, GPU, rope scaling, report) in about ten minutes.",
    },
    "wave1a": {
        "title": "yarn-niah wave1a short",
        "model": "Qwen/Qwen2.5-7B-Instruct",
        "lengths": "4096,8192,16384,32768",
        "depths": "0.0,0.1,0.25,0.5,0.75,0.9,1.0",
        "extra": ["--load-in-4bit", "--attn", "sdpa"],
        "max_new_tokens": 64,
        "why": "7B inside and at the edge of its 32k window: the short-context price of "
               "static YaRN, which Qwen's own card warns about.",
    },
    "wave1b": {
        "title": "yarn-niah wave1b long",
        "model": "Qwen/Qwen2.5-7B-Instruct",
        "lengths": "65536,131072",
        "depths": "0.1,0.5,0.9",
        "extra": ["--load-in-4bit", "--attn", "sdpa"],
        "max_new_tokens": 64,
        "why": "7B far past its window: 3 depths only, because 128k prefill dominates and "
               "a kernel that times out returns nothing.",
    },
}

# @@TOKENS@@ rather than .format(): the body is full of f-strings and dict literals,
# and escaping every brace is a good way to introduce a bug that only shows up on a
# GPU. render() asserts no token is left behind.
TEMPLATE = '''#!/usr/bin/env python3
"""@@TITLE@@

@@WHY@@

Generated by kaggle/build_kernels.py - do not edit by hand.
Preset @@SLUG@@ on @@SHAPE@@, harness pinned to @@COMMIT@@.

model  : @@MODEL@@
lengths: @@LENGTHS@@
depths : @@DEPTHS@@
extra  : @@EXTRA_PRETTY@@
"""
import collections
import glob
import importlib.metadata as md
import os
import shutil
import subprocess
import sys

REPO_URL = "@@REPO_URL@@"
COMMIT = "@@COMMIT@@"
WORK = "/kaggle/working"
MODEL = "@@MODEL@@"
LENGTHS = "@@LENGTHS@@"
DEPTHS = "@@DEPTHS@@"
EXTRA = @@EXTRA_REPR@@
MAX_NEW_TOKENS = @@MNT@@
SLUG = "@@SLUG@@"

def scratch_dir():
    """A writable, roomy directory that is NOT part of the kernel's output.

    Putting HF_HOME under /kaggle/working made `kernels output` fetch the entire
    model and dataset cache - hundreds of megabytes per pull, for data we already
    have. /kaggle/temp is scratch and stays out of the output.
    """
    for candidate in ("/kaggle/temp", "/tmp"):
        try:
            os.makedirs(candidate, exist_ok=True)
            return candidate
        except OSError:
            continue
    return os.path.join(WORK, "scratch")


os.environ.setdefault("HF_HOME", os.path.join(scratch_dir(), "hf"))
# Long-context prefill fragments the allocator; the OOM message itself suggests this.
os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")


def sh(cmd, check=True):
    """Stream a subprocess, and on failure raise with its last lines.

    A bare CalledProcessError hides the only thing worth reading.
    """
    print("$", " ".join(cmd), flush=True)
    tail = collections.deque(maxlen=40)
    with subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          text=True, bufsize=1) as proc:
        for line in proc.stdout:
            print(line, end="", flush=True)
            tail.append(line.rstrip())
        proc.wait()
    if check and proc.returncode:
        raise SystemExit("command failed ({}):\\n  {}".format(proc.returncode, "\\n  ".join(tail)))


def version(pkg):
    try:
        return md.version(pkg)
    except md.PackageNotFoundError:
        return None


def main():
    os.makedirs(WORK, exist_ok=True)
    os.chdir(WORK)

    # 1. Harness at the pinned commit. Pinning matters: these numbers get compared
    #    against a later run, and "main moved" explains nothing.
    # Clone into scratch, not WORK: everything under WORK becomes the kernel's
    # output, and shipping the entire git checkout (.git/hooks, FETCH_HEAD, config)
    # next to two JSONLs is noise.
    harness = os.path.join(scratch_dir(), "yarn-haystack")
    if not os.path.isdir(harness):
        sh(["git", "clone", "-q", REPO_URL, harness])
    os.chdir(harness)
    sh(["git", "fetch", "-q", "--all"])
    sh(["git", "checkout", "-q", COMMIT])
    head = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    if head != COMMIT:
        raise SystemExit("harness is at {}, expected {}".format(head, COMMIT))
    sys.path.insert(0, os.getcwd())
    print("harness commit:", head)

    # 2. Install only what is missing. The image already ships a CUDA-matched torch,
    #    and upgrading matplotlib/datasets provokes conflicts with preinstalled tools
    #    for no benefit here.
    need = []
    tf = version("transformers")
    if tf is None or tuple(int(x) for x in tf.split(".")[:2]) < (4, 51):
        need.append("transformers>=4.51")
    for pkg in ("accelerate", "datasets", "bitsandbytes"):
        if version(pkg) is None:
            need.append(pkg)
    if need:
        print("pip install:", " ".join(need), flush=True)
        sh([sys.executable, "-m", "pip", "install", "-q", "-U", *need])
    else:
        print("nothing to install - using what the image ships")
    for pkg in ("transformers", "torch", "accelerate", "datasets", "bitsandbytes", "matplotlib"):
        print("  {:14s} {}".format(pkg, version(pkg)))

    import torch
    print("\\ntorch {} | cuda {} | gpus {}".format(
        torch.__version__, torch.cuda.is_available(), torch.cuda.device_count()))
    for i in range(torch.cuda.device_count()):
        props = torch.cuda.get_device_properties(i)
        print("  gpu{}: {}, {:.1f} GiB".format(i, props.name, props.total_memory / 2 ** 30))
    if not torch.cuda.is_available():
        raise SystemExit("no CUDA - this kernel was pushed without a GPU")
    tf = version("transformers")
    if tf is None or tuple(int(x) for x in tf.split(".")[:2]) < (4, 51):
        raise SystemExit("need transformers>=4.51, have {}".format(tf))

    # 3. Preflight. Internet is off by default on Kaggle and is the usual cause of a
    #    one-second death; the corpus check separates a download problem from a
    #    harness problem.
    import urllib.request
    try:
        print("huggingface.co ->",
              urllib.request.urlopen("https://huggingface.co", timeout=20).status)
    except Exception as exc:
        raise SystemExit("no internet in this kernel: {!r} (Kaggle needs phone "
                         "verification for that)".format(exc))
    import niah
    text = niah.load_corpus(None, os.path.join(os.getcwd(), "cache"))
    print("corpus OK: {:.1f}M chars cached".format(len(text) / 1e6))

    # 4. Both arms on an identical grid. check=False so that one failing arm still
    #    leaves the other's results and the report: a killed 128k case should cost
    #    one case, not the session.
    results = os.path.join(WORK, "results")
    os.makedirs(results, exist_ok=True)

    # Carry results over from previous runs, mounted as a dataset source. Without
    # this the harness's resumable JSONL is dead code on Kaggle: every pushed
    # version gets a fresh /kaggle/working, so run.py finds nothing to skip and
    # recomputes every case - including the model download, twice per run, once per
    # arm.
    restored = []
    for prior in sorted(glob.glob("/kaggle/input/*/results/*.jsonl") +
                        glob.glob("/kaggle/input/*/*.jsonl")):
        dest = os.path.join(results, os.path.basename(prior))
        if not os.path.exists(dest):
            shutil.copy(prior, dest)
            restored.append(os.path.basename(prior))
    print("restored from previous runs:", restored or "(nothing)")

    common = ["--model", MODEL, "--lengths", LENGTHS, "--depths", DEPTHS,
              "--max-new-tokens", str(MAX_NEW_TOKENS), *EXTRA]
    for arm, extra in (("base", []), ("yarn", ["--factor", "4", "--original-max", "32768"])):
        out = os.path.join(results, "{}_{}.jsonl".format(arm, SLUG))
        print("\\n" + "=" * 72 + "\\n== ARM {}\\n".format(arm) + "=" * 72, flush=True)
        sh([sys.executable, "-u", "run.py", *common, "--arm", arm, *extra, "--out", out],
           check=False)

    # 5. Report. analyze.py copes with a partial run, so this is worth doing even if
    #    an arm was cut short: you get the heatmap for whatever finished.
    found = sorted(glob.glob(os.path.join(results, "*.jsonl")))
    print("\\nresult files:", found)
    if not found:
        raise SystemExit("no results were produced - read the output above")
    report = os.path.join(WORK, "report_" + SLUG)
    sh([sys.executable, "analyze.py", *found, "--outdir", report])
    summary = os.path.join(report, "summary.md")
    if os.path.exists(summary):
        print("\\n" + open(summary, encoding="utf-8").read())
    print("\\noutputs under", WORK, ":")
    for path in found + sorted(glob.glob(os.path.join(report, "*"))):
        print("  ", path)

    # The output endpoint is unusable for these runs: `kaggle kernels output` returns
    # nothing, with or without --file-pattern and with explicit versions, while
    # `kernels logs` works (when it answers at all - it is flaky too, so
    # kaggle/from_log retries). Echo every row with a prefix and let
    # tools/log_to_results.py rebuild the files: otherwise the measurements exist
    # only inside a container that is already gone.
    print("\\n===== NIAH_TRANSPORT_BEGIN =====")
    for path in found:
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                if line.strip():
                    print("NIAH_ROW " + line.strip())
    if os.path.exists(summary):
        with open(summary, encoding="utf-8") as fh:
            for line in fh:
                print("NIAH_MD " + line.rstrip())
    print("===== NIAH_TRANSPORT_END =====")


if __name__ == "__main__":
    main()
'''


def render(preset: dict, slug: str, commit: str, shape: str) -> str:
    tokens = dict(preset)
    tokens.update(
        slug=slug, commit=commit, shape=shape, repo_url=REPO_URL,
        extra_pretty=" ".join(preset["extra"]) if preset["extra"] else "(none)",
        extra_repr=repr(preset["extra"]),
        mnt=preset["max_new_tokens"],
    )
    out = TEMPLATE
    for key, value in tokens.items():
        out = out.replace(f"@@{key.upper()}@@", str(value))
    leftovers = [ln for ln in out.split("\n") if "@@" in ln]
    assert not leftovers, f"unsubstituted tokens: {leftovers[:3]}"
    return out


def build(slug: str, preset: dict, commit: str, user: str, shape: str,
          results_dataset: str = "") -> str:
    folder = os.path.join(HERE, slug)
    os.makedirs(folder, exist_ok=True)

    script_path = os.path.join(folder, f"{slug}.py")
    with open(script_path, "w", encoding="utf-8") as fh:
        fh.write(render(preset, slug, commit, shape))

    meta = {
        # Kernel slugs are global per user, so prefix them.
        "id": f"{user}/yarn-niah-{slug}",
        # Kaggle derives the URL slug from the title when they disagree, and then the
        # id in this file does not resolve - which is exactly what happened to the
        # attention probe and to wave1a (yarn-niah-wave1a vs ...-wave1a-short).
        "title": f"yarn-niah-{slug}",
        "code_file": f"{slug}.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": "true",       # a half-finished run is not for the world
        "enable_gpu": "true",
        "enable_tpu": "false",
        "enable_internet": "true",  # mandatory: model and corpus downloads
        "machine_shape": shape,     # NvidiaTeslaT4 == 2xT4, 32 GiB total
        # Results from earlier runs live in this dataset so run.py can skip
        # finished cases instead of recomputing them in a fresh container.
        "dataset_sources": [results_dataset] if results_dataset else [],
        "competition_sources": [],
        "kernel_sources": [], "model_sources": [],
    }
    with open(os.path.join(folder, "kernel-metadata.json"), "w", encoding="utf-8") as fh:
        json.dump(meta, fh, indent=2)
    return script_path


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--commit", required=True, help="harness commit the kernels must run")
    ap.add_argument("--user", default="nikitaprogart", help="Kaggle username (metadata id)")
    ap.add_argument("--shape", default="NvidiaTeslaT4", choices=["NvidiaTeslaT4", "NvidiaTeslaP100"])
    ap.add_argument("--only", default=None, help="build a single preset")
    ap.add_argument("--results-dataset", default="nikitaprogart/yarn-niah-results",
                    help="Kaggle dataset holding results from earlier runs, mounted read-only "
                         "at /kaggle/input so run.py can resume; empty string to disable")
    args = ap.parse_args()

    if len(args.commit) != 40:
        raise SystemExit(f"--commit must be a full 40-char sha, got {args.commit!r}")
    if args.only and args.only not in PRESETS:
        raise SystemExit(f"unknown preset {args.only!r}; have {sorted(PRESETS)}")

    for slug, preset in PRESETS.items():
        if args.only and slug != args.only:
            continue
        path = build(slug, preset, args.commit, args.user, args.shape, args.results_dataset)
        print(f"built {slug:8s} -> {os.path.relpath(path)}")


if __name__ == "__main__":
    main()
